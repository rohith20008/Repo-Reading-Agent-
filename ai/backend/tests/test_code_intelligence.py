def test_second_run_parses_nothing(client, parsed, settings):
    repo_id, first = parsed
    before = _row_counts(settings)
    second = run_parse(client, repo_id)
    assert second["parsedFiles"] == 0 and second["partialFiles"] == 0 and second["unsupportedFiles"] == 0
    assert second["skippedFiles"] == 0 and second["unchangedFiles"] == first["totalFiles"]
    assert _row_counts(settings) == before  # no duplicated rows


def _row_counts(settings):
    con = sqlite3.connect(settings.db_path)
    counts = {t: con.execute(f"select count(*) from {t}").fetchone()[0] for t in ("code_files", "symbols", "imports", "relations")}
    con.close()
    return counts


