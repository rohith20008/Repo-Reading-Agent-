def wait_parse(client, run_id, timeout=30):
    deadline = time.time() + timeout
    while time.time() < deadline:
        data = client.get(f"/api/parse-runs/{run_id}").json()
        if data["status"] in ("completed", "failed"):
            return data
        time.sleep(0.05)
    raise AssertionError("parse did not finish")


def run_parse(client, repo_id, **body):
    response = client.post(f"/api/repositories/{repo_id}/parse", json=body)
    assert response.status_code == 202, response.text
    return wait_parse(client, response.json()["runId"])


def imports_of(client, repo_id, path):
    data = client.get(f"/api/repositories/{repo_id}/imports", params={"path": path}).json()
    return {i["module"]: i for i in data["items"]}


